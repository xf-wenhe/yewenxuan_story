def main(apply):
    txt = io.open(PATH, 'rb').read().decode('utf-8').replace(u'\r\n', u'\n')
    lines = txt.split(u'\n')
    recs, bad = [], 0
    for ln, old, new in RECS:
        if not (0 < ln <= len(lines)):
            print('ABORT L%d: out of range' % ln)
            bad += 1
            continue
        if lines[ln - 1] != old:
            print('ABORT L%d: line does not match\n  got: %s\n  had: %s'
                  % (ln, lines[ln - 1][:70], old[:70]))
            bad += 1
            continue
        recs.append({'path': PATH, 'line': ln, 'old': old, 'new': new})

    print('%-6s %5s %5s %5s' % ('line', 'old', 'new', 'd'))
    total = 0
    for r in recs:
        a, b = len(CJK.findall(r['old'])), len(CJK.findall(r['new']))
        total += b - a
        print('L%-5d %5d %5d %+5d' % (r['line'], a, b, b - a))
    before = len(CJK.findall(txt))
    print('\ncjk %d -> %d  (%+d)   headroom 28 -> %d'
          % (before, before + total, total, 28 + total))
    print('records %d  problems %d' % (len(recs), bad))
    if bad:
        raise SystemExit(1)
    if apply:
        recs.sort(key=lambda r: -r['line'])
        io.open('tools/r325i_sites.json', 'w', encoding='utf-8', newline='\n').write(
            json.dumps({'round': 'R325', 'batch': 'i',
                        'note': 'ch571: template clauses rebuilt at the original '
                                'length, no headroom to delete anything',
                        'floor': 3000, 'records': recs},
                       ensure_ascii=False, indent=1))
        print('wrote tools/r325i_sites.json')


main('--apply' in sys.argv)
