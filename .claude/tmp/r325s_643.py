def main(apply):
    txt = io.open(PATH, 'rb').read().decode('utf-8').replace(u'\r\n', u'\n')
    lines = txt.split(u'\n')
    recs, bad, total = [], 0, 0
    for ln, old, new in RECS:
        if not (0 < ln <= len(lines)) or lines[ln - 1] != old:
            print('ABORT L%d: line does not match' % ln)
            bad += 1
            continue
        a = len(CJK.findall(old))
        b = 0 if new is None else len(CJK.findall(new))
        total += b - a
        mark = '  <-- ' if abs(b - a) > 4 else ''
        print('L%-4d %3d -> %3d  (%+4d)%s' % (ln, a, b, b - a, mark))
        recs.append({'path': PATH, 'line': ln, 'old': old, 'new': new})
    before = len(CJK.findall(txt))
    print('cjk %d -> %d  (%+d)   headroom 188 -> %d'
          % (before, before + total, total, 188 + total))
    print('records %d  problems %d' % (len(recs), bad))
    if bad:
        raise SystemExit(1)
    recs.sort(key=lambda r: -r['line'])
    if apply:
        io.open('tools/r325s_sites.json', 'w', encoding='utf-8', newline='\n').write(
            json.dumps({'round': 'R325', 'batch': 's',
                        'note': 'ch643: thirteen copies of one nose-sting, ten '
                                'explanations of one flat voice, two verbatim vows',
                        'floor': 3000, 'records': recs},
                       ensure_ascii=False, indent=1))
        print('wrote tools/r325s_sites.json')


