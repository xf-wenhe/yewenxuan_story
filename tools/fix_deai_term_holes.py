PATHS = sorted(set(EDITS) | set(EDITS2) | set(PERIODS))


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else '--dry-run'
    only = sys.argv[2] if len(sys.argv) > 2 else None
    if mode == '--verify':
        for path in PATHS:
            if only and only not in path:
                continue
            head = subprocess.run(['git', 'show', 'HEAD:' + path],
                                  capture_output=True, check=True).stdout
            rebuilt, r1 = apply_set(decode(head), EDITS.get(path, []))
            rebuilt, r2 = apply_set(rebuilt, EDITS2.get(path, []))
            lines, r3 = apply_periods(rebuilt.split('\n'), PERIODS.get(path, []))
            bad = 0
            for label, rows in (('stage1', r1), ('stage2', r2)):
                miss = [r for r in rows if not r[2]]
                bad += len(miss)
                print('    %-6s %3d edits, %d problem(s)' % (label, len(rows), len(miss)))
                for r in miss:
                    print('       !! %r' % r[0][-24:])
            miss = [r for r in r3 if not r[2]]
            bad += len(miss)
            print('    %-6s %3d edits, %d problem(s)' % ('period', len(r3), len(miss)))
            for ln, expected, ok, actual in miss:
                print('       !! L%d %r != %r' % (ln, expected[-12:], actual))
            same = bad == 0 and encode('\n'.join(lines), head) == read_bytes(path)
            print('%-44s reconstruction %s' % (path, 'OK' if same else 'MISMATCH'))
        return 0
    total = bad = 0
    for path, (raw, mid, final, rows1, rows2, rows3) in plan().items():
        if only and only not in path:
            continue
        groups = (('stage1', rows1, mid), ('stage2', rows2, final))
        for label, rows, src in groups:
            hits = sum(r[3] for r in rows)
            miss = [r for r in rows if not r[2]]
            total += len(rows)
            bad += len(miss)
            print('%-44s %-6s %3d edits, %3d occurrences, %d not unique/overlapping'
                  % (path, label, len(rows), hits, len(miss)))
            for r in miss:
                print('    !! count=%d  %r' % (r[3], r[0][-24:]))
            if mode == '--preview':
                for old, new, ok, n, i, j in rows:
                    if not ok:
                        continue
                    print('    L%-4d %s' % (src.count('\n', 0, i) + 1,
                                            old.replace('\n', '\\n')))
                    print('         -> %s' % new.replace('\n', '\\n'))
        miss = [r for r in rows3 if not r[2]]
        total += len(rows3)
        bad += len(miss)
        print('%-44s %-6s %3d edits, %3d occurrences, %d line(s) not as expected'
              % (path, 'period', len(rows3), len(rows3) - len(miss), len(miss)))
        for ln, expected, ok, actual in miss:
            print('    !! L%d %r != %r' % (ln, expected[-12:], actual))
        if mode == '--preview':
            for ln, expected, ok, actual in rows3:
                if ok:
                    print('    L%-4d %s。' % (ln, expected[-20:]))
    print('TOTAL %d edits, %d problems' % (total, bad))
    if mode == '--apply':
        if bad:
            print('ABORT: fix the problems first')
            return 1
        for path, (raw, mid, final, rows1, rows2, rows3) in plan().items():
            if only and only not in path:
                continue
            with open(path, 'wb') as f:
                f.write(encode(final, raw))
            print('wrote %s' % path)
    return 0


if __name__ == '__main__':
    sys.exit(main())
