def read_bytes(path):
    with open(path, 'rb') as f:
        return f.read()


def decode(raw):
    return raw.decode('utf-8-sig' if raw[:3] == b'\xef\xbb\xbf' else 'utf-8')


def encode(text, raw):
    return text.encode('utf-8-sig' if raw[:3] == b'\xef\xbb\xbf' else 'utf-8')


def apply_set(text, pairs):
    """-> (text, rows) with rows = [old, new, ok, count, start, end]

    ok is False when the OLD string is not unique, or when its span overlaps a
    span already claimed by another edit of the same set (an overlap would make
    the later replace a silent no-op).
    """
    rows, spans = [], []
    for old, new in pairs:
        n = text.count(old)
        i = text.index(old) if n == 1 else -1
        ok = n == 1
        end = -1
        if ok:
            j = i + len(old)
            if any(i < b and a < j for a, b in spans):
                ok = False
            else:
                spans.append((i, j))
                end = j
        rows.append([old, new, ok, n, i, end])
    for old, new, ok, n, i, j in sorted(rows, key=lambda r: -r[4]):
        if ok:
            assert text[i:i + len(old)] == old, 'edit moved: %r' % old[-24:]
            text = text[:i] + new + text[i + len(old):]
    return text, rows


def apply_periods(lines, spec):
    """-> (lines, rows) with rows = [ln, expected, ok, actual]

    Keyed on the line number plus the exact line content: two neighbouring
    paragraphs of ch779 share their whole tail, so no text anchor can be unique
    there.  A line that does not read back exactly as recorded is left alone.
    """
    rows = [[ln, expected, 0 < ln <= len(lines) and lines[ln - 1] == expected,
             lines[ln - 1] if 0 < ln <= len(lines) else None]
            for ln, expected in spec]
    for ln, expected, ok, actual in rows:
        if ok:
            lines[ln - 1] = expected + '。'
    return lines, rows


