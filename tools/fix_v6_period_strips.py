def read_state_of(raw):
    """-> (raw, lines, term, problem)  term is the file's own line terminator"""
    text = raw.decode('utf-8-sig' if raw[:3] == BOM else 'utf-8')
    crlf = text.count('\r\n')
    lf = text.count('\n') - crlf
    if crlf and lf:
        return raw, None, None, 'MIXED-EOL (%d crlf, %d lf)' % (crlf, lf)
    term = '\r\n' if crlf else '\n'
    return raw, text.split(term), term, None


def read_state(path):
    with open(path, 'rb') as f:
        return read_state_of(f.read())


def encode(lines, term, raw):
    return term.join(lines).encode('utf-8-sig' if raw[:3] == BOM else 'utf-8')


def sites_of(path):
    return SITES.get(path, []) + SITES2.get(path, [])


def sites_for(path, stage2):
    """the text-keyed table for the requested stage"""
    return SITES2.get(path, []) if stage2 else sites_of(path)


def byline_for(path, stage2):
    """the line-keyed table -- stage 1 only"""
    return [] if stage2 else BYLINE.get(path, [])


def resolve(lines, sites, byline):
    """-> rows [kind, tier, line, targets, detail]

    Collects every target first so a text-keyed and a line-keyed edit can never
    land on the same line, then the caller applies them.
    """
    rows = []
    for tier, old in sites:
        idx = [i for i, L in enumerate(lines) if L == old]
        rows.append(['text', tier, old, idx if len(idx) == 1 else [], len(idx)])
    for ln, tier, old in byline:
        ok = 0 < ln <= len(lines) and lines[ln - 1] == old
        rows.append(['line', tier, old, [ln - 1] if ok else [], ln])
    return rows


def commit(lines, rows):
    seen = set()
    for row in rows:
        keep = []
        for t in row[3]:
            if t in seen:
                row[4] = 'OVERLAP'
                continue
            seen.add(t)
            keep.append(t)
        row[3] = keep
    for row in rows:
        for t in row[3]:
            lines[t] = row[2] + PERIOD
    return rows


def audit(path):
    """re-derive the tier evidence from the parent commit"""
    r = subprocess.run(['git', 'show', '%s:%s' % (PARENT, path)], capture_output=True)
    if r.returncode:
        return None, 'parent commit missing the file'
    ptext = r.stdout.decode('utf-8-sig')
    cut = ptext.count('\r\n')
    ptext = ptext.replace('\r\n', '\n')
    plines = [x for x in ptext.split('\n')]
    pnz = set()
    pbare = set()
    for x in plines:
        pnz.add(nz(x))
        if x.endswith(PERIOD):
            pbare.add(bare(x))
    pnztext = nz(ptext)
    kinds = {}
    for tier, old in sites_of(path):
        got = tier_of(old, pnz, pnztext, pbare, plines)
        if got != tier:
            kinds.setdefault('MISMATCH', []).append((tier, got, old))
    return kinds, None


def nz(t):
    return t.replace('"', '')


def bare(t):
    return ''.join(c for c in t if '\u4e00' <= c <= '\u9fff' or c.isalnum())


def lcs(a, b):
    n = 0
    while n < len(a) and n < len(b) and a[-1 - n] == b[-1 - n]:
        n += 1
    return n


def tier_of(s, pnz, pnztext, pbare, plines):
    ns, bs = nz(s), bare(s)
    if ns + PERIOD in pnz:
        return 'exact'
    if len(bs) >= 12 and ns + PERIOD in pnztext:
        return 'sub'
    if bs in pbare:
        return 'cjk'
    for x in plines:
        if x.endswith(PERIOD):
            b = bare(x)
            if lcs(bs, b) >= 12 and abs(len(bs) - len(b)) <= max(10, len(b) // 4):
                return 'suffix'
    return None


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else '--dry-run'
    only = sys.argv[2] if len(sys.argv) > 2 else None
    stage2 = mode.endswith('2')
    write = mode.startswith('--apply')
    paths = sorted(set(SITES2) if stage2
                   else (set(SITES) | set(SITES2) | set(BYLINE)))
    if mode == '--verify':
        for path in paths:
            if only and only not in path:
                continue
            head = subprocess.run(['git', 'show', 'HEAD:' + path],
                                  capture_output=True, check=True).stdout
            raw, lines, term, prob = read_state(path)
            if prob:
                print('%-44s %s' % (path, prob))
                continue
            _, hlines, hterm, _ = read_state_of(head)
            if hterm != term:
                print('%-44s EOL differs from HEAD' % path)
            rows = commit(hlines, resolve(hlines, sites_of(path),
                                          BYLINE.get(path, [])))
            bad = [r for r in rows if not r[3]]
            same = not bad and encode(hlines, term, head) == raw
            print('%-44s %3d edits, %d problem(s), reconstruction %s'
                  % (path, len(rows), len(bad), 'OK' if same else 'MISMATCH'))
            for r in bad:
                print('    !! %s %r' % (r[4], r[2][-24:]))
        return 0
    if mode == '--audit':
        bad = 0
        for path in paths:
            kinds, err = audit(path)
            if err:
                print('%-44s %s' % (path, err))
                bad += 1
                continue
            n = len(sites_of(path)) + len(BYLINE.get(path, []))
            print('%-44s %3d sites, %s' % (path, n, 'evidence OK' if not kinds else kinds))
            bad += 1 if kinds else 0
        print('audit: %d file(s) with problems' % bad)
        return 1 if bad else 0
    total = bad = 0
    for path in paths:
        if only and only not in path:
            continue
        raw, lines, term, prob = read_state(path)
        if prob:
            print('%-44s ABORT %s' % (path, prob))
            bad += 1
            continue
        rows = commit(lines, resolve(lines, sites_for(path, stage2),
                                     byline_for(path, stage2)))
        miss = [r for r in rows if not r[3]]
        total += len(rows)
        bad += len(miss)
        tiers = {}
        for r in rows:
            if r[3]:
                tiers[r[1]] = tiers.get(r[1], 0) + 1
        print('%-44s %3d edits  %s  %d problem(s)'
              % (path, len(rows), tiers, len(miss)))
        for r in miss:
            print('    !! %s hits  %r' % (r[4], r[2][-28:]))
        if mode == '--preview':
            for r in rows:
                if r[3]:
                    print('    L%-4d ...%s。' % (r[3][0] + 1, r[2][-36:]))
    print('TOTAL %d edits, %d problems' % (total, bad))
    if write:
        if bad:
            print('ABORT: fix the problems first')
            return 1
        for path in paths:
            if only and only not in path:
                continue
            raw, lines, term, prob = read_state(path)
            if prob:
                continue
            commit(lines, resolve(lines, sites_for(path, stage2),
                                  byline_for(path, stage2)))
            with open(path, 'wb') as f:
                f.write(encode(lines, term, raw))
            print('wrote %s' % path)
    return 0


if __name__ == '__main__':
    sys.exit(main())
