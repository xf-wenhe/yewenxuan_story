def count_cjk(text):
    return len(re.findall(r'[一-鿿]', text))


def cn_numeral(ch):
    """Convert chapter number to Chinese numeral, e.g. 124 -> 一百二十四."""
    cn_digits = '零一二三四五六七八九'
    s = str(ch)
    n = len(s)
    if n == 1:
        return cn_digits[int(s[0])]
    if n == 2:
        if s[0] == '1' and s[1] == '0':
            return '十'
        elif s[0] == '1':
            return '十' + cn_digits[int(s[1])]
        else:
            return cn_digits[int(s[0])] + '十'
    if n == 3:
        h = int(s[0])
        result = ('两' if h == 2 else cn_digits[h]) + '百'
        if s[1] == '0':
            if s[2] != '0':
                result += '零' + cn_digits[int(s[2])]
        elif s[1] == '1':
            result += '十一'
            if s[2] != '0':
                result += cn_digits[int(s[2])]
        else:
            result += cn_digits[int(s[1])] + '十'
            if s[2] != '0':
                result += cn_digits[int(s[2])]
        return result
    return s


def find_end_marker_v2(text, ch):
    """Find Chinese numeral end marker for V2/V3."""
    cn = cn_numeral(ch)
    marker = f'（第{cn}章完）'
    if marker in text:
        return marker
    # Also try Arabic numeral format
    marker2 = f'（第{ch}章完）'
    if marker2 in text:
        return marker2
    return None


def process_v2():
    for ch, pad in sorted(PAD_V2.items()):
        path = rf'D:\work\yewenxuan_story\chapters\volume-2\chapter-{ch}-polished.md'
        with open(path, 'r', encoding='utf-8') as f:
            text = f.read()

        orig = count_cjk(text)
        pad_cjk = count_cjk(pad)

        end_marker = find_end_marker_v2(text, ch)
        if end_marker is None:
            print(f'V2 ch{ch}: ERROR - end marker not found!')
            continue

        count = text.count(end_marker)
        if count > 1:
            last_idx = text.rfind(end_marker)
            first_part = text[:last_idx]
            first_part = first_part.replace(end_marker, '')
            text = first_part + end_marker
            print(f'V2 ch{ch}: removed {count-1} duplicate end marker(s)')

        idx = text.rfind(end_marker)
        new_text = text[:idx] + '\n\n' + pad + '\n\n' + text[idx:]
        new_cjk = count_cjk(new_text)

        with open(path, 'w', encoding='utf-8') as f:
            f.write(new_text)

        status = 'OK' if new_cjk >= 3000 else 'LOW'
        print(f'[{status}] V2 ch{ch}: {orig} -> {new_cjk} (added {pad_cjk} CJK)')


