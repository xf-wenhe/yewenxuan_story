import re, os

def count_cjk(text):
    return len(re.findall(r'[一-鿿]', text))

def cn_numeral(ch):
    cn_digits = '零一二三四五六七八九'
    s = str(ch)
    n = len(s)
    if n == 1:
        return cn_digits[int(s[0])]
    if n == 2:
        if s[0] == '1' and s[1] == '0':
            return '十'
        elif s[0] == '1':
            return '十' + cn_digits[int(s[1])]
        else:
            return cn_digits[int(s[0])] + '十' + cn_digits[int(s[1])]
    if n == 3:
        h = int(s[0])
        result = cn_digits[h] + '百'
        if s[1] == '0':
            if s[2] != '0':
                result += '零' + cn_digits[int(s[2])]
        elif s[1] == '1':
            result += '一十'
            if s[2] != '0':
                result += cn_digits[int(s[2])]
        else:
            result += cn_digits[int(s[1])] + '十'
            if s[2] != '0':
                result += cn_digits[int(s[2])]
        return result
    return s

