def find_end_marker(text, ch):
    cn = cn_numeral(ch)
    marker = f'（第{cn}章完）'
    if marker in text:
        return marker
    marker2 = f'（第{ch}章完）'
    if marker2 in text:
        return marker2
    return None


def pad_chapter(ch, pad, volume, special_ch393=False):
    path = f'D:\\work\\yewenxuan_story\\chapters\\volume-{volume}\\chapter-{ch}-polished.md'
    with open(path, 'r', encoding='utf-8') as f:
        text = f.read()

    orig = count_cjk(text)
    pad_cjk = count_cjk(pad)

    if special_ch393:
        dup = '闭环里的嗡鸣声在那一刻好像也软了一点，像整片海都跟着松了一口气'
        count = text.count(dup)
        if count > 1:
            first_idx = text.find(dup)
            rest = text[first_idx + len(dup):]
            rest = rest.replace(dup, '')
            text = text[:first_idx + len(dup)] + rest
            print(f'[FIX] V{volume} ch{ch}: removed {count-1} duplicate sentence(s)')

        cn = cn_numeral(ch)
        end_marker = f'（第{cn}章完）'
        text = text.rstrip() + '\n\n' + end_marker + '\n'
        print(f'[FIX] V{volume} ch{ch}: added end marker')
    else:
        end_marker = find_end_marker(text, ch)
        if end_marker is None:
            print(f'[ERR] V{volume} ch{ch}: end marker not found!')
            return

        count = text.count(end_marker)
        if count > 1:
            last_idx = text.rfind(end_marker)
            first_part = text[:last_idx]
            first_part = first_part.replace(end_marker, '')
            text = first_part + end_marker
            print(f'[FIX] V{volume} ch{ch}: removed {count-1} duplicate end marker(s)')

    idx = text.rfind(end_marker)
    new_text = text[:idx] + '\n\n' + pad + '\n\n' + text[idx:]
    new_cjk = count_cjk(new_text)

    with open(path, 'w', encoding='utf-8') as f:
        f.write(new_text)

    status = 'OK' if new_cjk >= 3000 else 'LOW'
    print(f'[{status}] V{volume} ch{ch}: {orig} -> {new_cjk} (added {pad_cjk} CJK)')


