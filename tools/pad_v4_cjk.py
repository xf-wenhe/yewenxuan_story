def count_cjk(text):
    return len(re.findall(r'[一-鿿]', text))


def find_end_marker(text, ch):
    """Find the correct end marker for a chapter. Some use Arabic, some use Chinese numerals."""
    # Try Arabic numerals first (e.g. ch468 uses 第468章完)
    for marker in [f'（第{ch}章完）']:
        if marker in text:
            return marker
    # Chinese numeral mapping: 415 = 四百一十五 (digit[0]百 + digit[1]十 + digit[2])
    cn_digits = '零一二三四五六七八九'
    s = str(ch)
    if len(s) == 3:
        cn = cn_digits[int(s[0])] + '百' + cn_digits[int(s[1])] + '十'
        if int(s[2]) != 0:
            cn += cn_digits[int(s[2])]
    marker = f'（第{cn}章完）'
    if marker in text:
        return marker
    return None


