        pad_cjk = count_cjk(pad)

        end_marker = find_end_marker(text, ch)
        if end_marker is None:
            print(f'ch{ch}: ERROR - end marker not found!')
            continue

        # Deduplicate markers (ch510 has two)
        count = text.count(end_marker)
        if count > 1:
            # Keep only the last occurrence
            last_idx = text.rfind(end_marker)
            first_part = text[:last_idx]
            first_part = first_part.replace(end_marker, '')
            text = first_part + end_marker
            print(f'ch{ch}: removed {count-1} duplicate end marker(s)')

        # Insert padding before the end marker
        idx = text.rfind(end_marker)
        new_text = text[:idx] + '\n' + pad + '\n\n' + text[idx:]
        new_cjk = count_cjk(new_text)

        with open(path, 'w', encoding='utf-8') as f:
            f.write(new_text)

        print(f'ch{ch}: {orig} -> {new_cjk} (added {pad_cjk} CJK)')


